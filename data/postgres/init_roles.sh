#!/bin/bash
set -e

# Подключаемся к базе, созданной Docker-ом (из $POSTGRES_DB)
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<-EOSQL
    CREATE ROLE "$BACKEND_USER" WITH LOGIN PASSWORD '$BACKEND_APP_PASS';
    CREATE ROLE "$RAG_USER" WITH LOGIN PASSWORD '$RAG_APP_PASS';
    
    REVOKE ALL ON SCHEMA public FROM PUBLIC;
    GRANT USAGE ON SCHEMA public TO "$BACKEND_USER";
    GRANT USAGE ON SCHEMA public TO "$RAG_USER";
    
    ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO "$BACKEND_USER";
    ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO "$BACKEND_USER";

    ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANTSELECT, INSERT, UPDATE, DELETE ON TABLES TO "$RAG_USER";
    ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO "$RAG_USER";
EOSQL